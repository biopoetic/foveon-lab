// sppgap turns a spp-check -save JSON into the body table the app shows in
// the photo info: one line per camera body, the mean 8-bit error against
// Sigma Photo Pro and the number of photos that number rests on.
//
//	go run ./tools/sppgap -json zz-out/task22/spp-check.json
//
// It writes sppgaps_gen.go (embedded in the app) and docs/spp-gap.md (the
// table a person can read). Re-run it after every spp-check; the app never
// guesses a gap and never reads the calibration folder at run time.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type score struct {
	Group string  `json:"group"`
	Model string  `json:"model"`
	All   float64 `json:"all"`
	Area  float64 `json:"area"`
	EV    float64 `json:"ev"`
}

type row struct {
	Body   string
	Model  string
	Mean   float64
	Area   float64
	Photos int
}

func main() {
	js := flag.String("json", "", "a spp-check -save JSON file (default: the newest spp-check*.json in the calibration folder)")
	dir := flag.String("dir", filepath.Join(os.Getenv("USERPROFILE"), "Desktop", "foveon-calibration"), "folder to find the newest spp-check*.json in")
	out := flag.String("out", "sppgaps_gen.go", "the Go table to write")
	md := flag.String("md", filepath.Join("docs", "spp-gap.md"), "the Markdown table to write")
	flag.Parse()

	path := *js
	if path == "" {
		ents, err := os.ReadDir(*dir)
		if err != nil {
			die("find the newest spp-check: %v", err)
		}
		var best string
		var bestMod int64
		for _, e := range ents {
			n := strings.ToLower(e.Name())
			if e.IsDir() || !strings.HasSuffix(n, ".json") || !strings.Contains(n, "spp-check") {
				continue
			}
			info, err := e.Info()
			if err != nil {
				continue
			}
			if info.ModTime().UnixNano() > bestMod {
				best, bestMod = filepath.Join(*dir, e.Name()), info.ModTime().UnixNano()
			}
		}
		if best == "" {
			die("no spp-check*.json in %s; give -json", *dir)
		}
		path = best
	}
	b, err := os.ReadFile(path)
	if err != nil {
		die("%v", err)
	}
	var scores map[string]score
	if err := json.Unmarshal(b, &scores); err != nil {
		die("%s is not a spp-check JSON: %v", path, err)
	}
	if len(scores) == 0 {
		die("%s has no scored photos", path)
	}
	type agg struct {
		model, group string
		n            int
		all, area    float64
	}
	by := map[string]*agg{}
	for _, s := range scores {
		// A reference this far off is another SPP setting, not our error
		// (spp-check reports the same photos as non-neutral).
		if math.Abs(s.EV) > 0.25 {
			continue
		}
		model := strings.TrimSpace(s.Model)
		if model == "" {
			model = strings.TrimSpace(s.Group)
		}
		if model == "" {
			model = "unknown body"
		}
		a := by[model]
		if a == nil {
			a = &agg{model: model, group: s.Group}
			by[model] = a
		}
		a.n++
		a.all += s.All
		a.area += s.Area
	}
	var rows []row
	for _, a := range by {
		rows = append(rows, row{
			Body:   strings.TrimSpace(strings.TrimPrefix(a.model, "SIGMA ")),
			Model:  a.model,
			Mean:   a.all / float64(a.n),
			Area:   a.area / float64(a.n),
			Photos: a.n,
		})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Body < rows[j].Body })

	source := filepath.ToSlash(path)
	var g strings.Builder
	fmt.Fprintf(&g, "// Code generated by go run ./tools/sppgap -json %s; DO NOT EDIT.\n\npackage main\n\n", source)
	fmt.Fprintf(&g, "// sppGapSource names the spp-check run the table was computed from.\nconst sppGapSource = %q\n\n", source)
	g.WriteString("// sppGaps is the per-body measured gap against Sigma Photo Pro, mean\n")
	g.WriteString("// absolute 8-bit error over every scored photo of that body.\n")
	g.WriteString("var sppGaps = []sppGap{\n")
	for _, r := range rows {
		fmt.Fprintf(&g, "\t{Body: %q, Model: %q, Mean: %.4f, Area: %.4f, Photos: %d},\n", r.Body, r.Model, r.Mean, r.Area, r.Photos)
	}
	g.WriteString("}\n")
	if err := os.WriteFile(*out, []byte(g.String()), 0o644); err != nil {
		die("write %s: %v", *out, err)
	}

	var m strings.Builder
	m.WriteString("# The measured gap against Sigma Photo Pro, by body\n\n")
	fmt.Fprintf(&m, "From `%s`: mean absolute 8-bit error over every scored photo of that body\n", source)
	m.WriteString("(`all` in `spp-check`; `area` is the same error on both images reduced 4×, so it\n")
	m.WriteString("ignores fine detail). The app shows the same line in the photo info.\n\n")
	m.WriteString("| body | mean /255 | area /255 | photos |\n")
	m.WriteString("|---|---:|---:|---:|\n")
	for _, r := range rows {
		fmt.Fprintf(&m, "| %s | %.1f | %.1f | %d |\n", r.Body, r.Mean, r.Area, r.Photos)
	}
	m.WriteString("\nRegenerate with:\n\n```\ngo run ./tools/sppgap -json ")
	m.WriteString(source)
	m.WriteString("\n```\n")
	if err := os.MkdirAll(filepath.Dir(*md), 0o755); err != nil {
		die("create %s: %v", filepath.Dir(*md), err)
	}
	if err := os.WriteFile(*md, []byte(m.String()), 0o644); err != nil {
		die("write %s: %v", *md, err)
	}
	fmt.Printf("%d bodies from %d photos -> %s, %s\n", len(rows), len(scores), *out, *md)
	for _, r := range rows {
		fmt.Printf("  %-22s %5.1f/255  area %5.1f  %3d photo%s\n", r.Body, r.Mean, r.Area, r.Photos, plural(r.Photos))
	}
}

func plural(n int) string {
	if n == 1 {
		return ""
	}
	return "s"
}

func die(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "sppgap: "+f+"\n", a...)
	os.Exit(1)
}
